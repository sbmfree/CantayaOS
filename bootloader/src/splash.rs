/// Total number of boot stages (for progress bar calculation)
pub const BOOT_STAGES: u32 = 8;

/// Boot stage identifiers
pub const STAGE_INIT: u32 = 0;
pub const STAGE_GOP: u32 = 1;
pub const STAGE_LOAD_KERNEL: u32 = 2;
pub const STAGE_PARSE_ELF: u32 = 3;
pub const STAGE_ACPI_SMBIOS: u32 = 4;
pub const STAGE_PAGE_TABLES: u32 = 5;
pub const STAGE_EXIT_BOOT: u32 = 6;
pub const STAGE_JUMP_KERNEL: u32 = 7;

/// Draw the initial boot splash screen.
///
/// Fills the framebuffer with a dark gradient background,
/// draws the CantayaOS title, version, and an empty progress bar.
pub fn draw_splash(fb: &FramebufferInfo) {
    let addr = fb.address;
    let w = fb.width;
    let h = fb.height;
    let stride = fb.stride;

    // 1. Dark blue gradient background
    for y in 0..h {
        let blue = 15 + ((y as u64 * 40) / h as u64) as u8; // 15..55
        let green = 5 + ((y as u64 * 15) / h as u64) as u8;  // 5..20
        for x in 0..w {
            put_pixel(addr, stride, x, y, 0, green, blue);
        }
    }

    // 2. Title box — centered
    let box_w = 700u32;
    let box_h = 180u32;
    let box_x = (w.saturating_sub(box_w)) / 2;
    let box_y = h / 4;

    // Outer border (bright accent line)
    fill_rect(addr, stride, box_x, box_y, box_w, 2, 0x40, 0x90, 0xFF);
    fill_rect(addr, stride, box_x, box_y + box_h - 2, box_w, 2, 0x40, 0x90, 0xFF);
    fill_rect(addr, stride, box_x, box_y, 2, box_h, 0x40, 0x90, 0xFF);
    fill_rect(addr, stride, box_x + box_w - 2, box_y, 2, box_h, 0x40, 0x90, 0xFF);

    // Inner fill (dark semi-transparent look)
    fill_rect(addr, stride, box_x + 2, box_y + 2, box_w - 4, box_h - 4, 0x08, 0x10, 0x28);

    // 3. Title text — "CantayaOS" at 4x scale (32px tall)
    let title = "CantayaOS";
    let title_px_w = title.len() as u32 * 8 * 4; // 4x scale
    let title_x = box_x + (box_w.saturating_sub(title_px_w)) / 2;
    let title_y = box_y + 30;
    draw_string(addr, stride, title_x, title_y, title, 4, 0x60, 0xB0, 0xFF);

    // 4. Version text — 2x scale
    let version = concat!("v", env!("CARGO_PKG_VERSION"), " - x86_64 UEFI Bootloader");
    let ver_px_w = version.len() as u32 * 8 * 2;
    let ver_x = box_x + (box_w.saturating_sub(ver_px_w)) / 2;
    let ver_y = title_y + 50;
    draw_string(addr, stride, ver_x, ver_y, version, 2, 0x80, 0x80, 0xA0);

    // 5. Tagline — 1x scale
    let tagline = "Windows NT-inspired Hybrid Kernel";
    let tag_px_w = tagline.len() as u32 * 8;
    let tag_x = box_x + (box_w.saturating_sub(tag_px_w)) / 2;
    let tag_y = ver_y + 30;
    draw_string(addr, stride, tag_x, tag_y, tagline, 1, 0x55, 0x55, 0x70);

    // 6. Progress bar background
    draw_progress_bar_background(fb);
}

/// Draw the progress bar background (empty bar).
fn draw_progress_bar_background(fb: &FramebufferInfo) {
    let bar_w = 500u32;
    let bar_h = 20u32;
    let bar_x = (fb.width.saturating_sub(bar_w)) / 2;
    let bar_y = fb.height * 3 / 4;

    // Bar outline
    fill_rect(fb.address, fb.stride, bar_x - 2, bar_y - 2, bar_w + 4, bar_h + 4, 0x30, 0x50, 0x80);
    // Bar interior (dark)
    fill_rect(fb.address, fb.stride, bar_x, bar_y, bar_w, bar_h, 0x10, 0x15, 0x25);
}

/// Update the progress bar and status message.
///
/// `stage` is the current boot stage (0..BOOT_STAGES-1).
/// `msg` is shown below the progress bar.
pub fn update_progress(fb: &FramebufferInfo, stage: u32, msg: &str) {
    let bar_w = 500u32;
    let bar_h = 20u32;
    let bar_x = (fb.width.saturating_sub(bar_w)) / 2;
    let bar_y = fb.height * 3 / 4;

    // Calculate filled portion
    let filled = if BOOT_STAGES > 0 {
        (bar_w * (stage + 1)) / BOOT_STAGES
    } else {
        0
    };

    // Draw filled portion (bright gradient)
    for dy in 0..bar_h {
        for dx in 0..filled {
            let intensity = 150 + ((dy as u16 * 60) / bar_h as u16) as u8;
            put_pixel(fb.address, fb.stride, bar_x + dx, bar_y + dy, 0x20, intensity / 2, intensity);
        }
    }

    // Clear old message area
    let msg_y = bar_y + bar_h + 12;
    fill_rect(fb.address, fb.stride, bar_x, msg_y, bar_w, 12, 0, 0, 0);

    // Draw new message (1x scale)
    let msg_px_w = msg.len() as u32 * 8;
    let msg_x = bar_x + (bar_w.saturating_sub(msg_px_w)) / 2;
    draw_string(fb.address, fb.stride, msg_x, msg_y, msg, 1, 0x80, 0x90, 0xB0);
}

/// Draw a fatal error message on the framebuffer.
///
/// Used for critical errors before or after ExitBootServices.
/// Displays a red-tinted screen with the error text.
#[allow(dead_code)]
pub fn draw_error(fb: &FramebufferInfo, error_msg: &str) {
    let addr = fb.address;
    let stride = fb.stride;

    // Dark red background
    fill_rect(addr, stride, 0, 0, fb.width, fb.height, 0x40, 0x00, 0x00);

    // Error header
    let header = "BOOT ERROR";
    let header_x = (fb.width.saturating_sub(header.len() as u32 * 24)) / 2;
    draw_string(addr, stride, header_x, 200, header, 3, 0xFF, 0x40, 0x40);

    // Error message
    let msg_x = (fb.width.saturating_sub(error_msg.len() as u32 * 16)) / 2;
    draw_string(addr, stride, msg_x, 300, error_msg, 2, 0xFF, 0xFF, 0xFF);

    // Instructions
    let hint = "System halted. Power off or reset to retry.";
    let hint_x = (fb.width.saturating_sub(hint.len() as u32 * 8)) / 2;
    draw_string(addr, stride, hint_x, 380, hint, 1, 0xA0, 0xA0, 0xA0);
}
