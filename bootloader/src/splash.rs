// ============================================================================
// Framebuffer Pixel Helpers
// ============================================================================

/// Write a single pixel to the framebuffer (BGR format, 4 bytes per pixel).
#[inline]
fn put_pixel(fb_addr: u64, stride: u32, x: u32, y: u32, r: u8, g: u8, b: u8) {
    let offset = (y as u64 * stride as u64 + x as u64) * 4;
    let ptr = (fb_addr + offset) as *mut u8;
    unsafe {
        ptr.write(b);
        ptr.add(1).write(g);
        ptr.add(2).write(r);
        ptr.add(3).write(0);
    }
}

/// Fill a rectangle with a solid color.
fn fill_rect(fb_addr: u64, stride: u32, x: u32, y: u32, w: u32, h: u32, r: u8, g: u8, b: u8) {
    for dy in 0..h {
        for dx in 0..w {
            put_pixel(fb_addr, stride, x + dx, y + dy, r, g, b);
        }
    }
}

/// Draw a single 8x8 character from the embedded font, scaled by `scale`.
fn draw_char(fb_addr: u64, stride: u32, x: u32, y: u32, ch: u8, scale: u32, r: u8, g: u8, b: u8) {
    if ch < 32 || ch > 126 {
        return;
    }
    let glyph = &FONT_8X8[(ch - 32) as usize];
    for row in 0..8u32 {
        let bits = glyph[row as usize];
        for col in 0..8u32 {
            if bits & (0x80 >> col) != 0 {
                // Draw a scale×scale block for this pixel
                for sy in 0..scale {
                    for sx in 0..scale {
                        put_pixel(
                            fb_addr, stride,
                            x + col * scale + sx,
                            y + row * scale + sy,
                            r, g, b,
                        );
                    }
                }
            }
        }
    }
}

/// Draw a string using the embedded font at the given position and scale.
pub fn draw_string(fb_addr: u64, stride: u32, x: u32, y: u32, s: &str, scale: u32, r: u8, g: u8, b: u8) {
    let mut cx = x;
    for ch in s.bytes() {
        if ch == b'\n' {
            break; // single-line only for splash
        }
        draw_char(fb_addr, stride, cx, y, ch, scale, r, g, b);
        cx += 8 * scale;
    }
}

